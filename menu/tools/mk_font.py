def parse():
    glyphs = {}
    for block in GLYPHS.strip().split("\n\n"):
        lines = block.strip().split("\n")
        code = int(lines[0], 16)
        rows = lines[1:]
        assert len(rows) == 8 and all(len(r) == 5 and set(r) <= {".", "#"} for r in rows), \
            "glyph %02X: need 8 rows of 5 '.'/'#'" % code
        assert code not in glyphs, "glyph %02X twice" % code
        glyphs[code] = rows
    assert sorted(glyphs) == list(range(0x20, 0x7F)), "need exactly ASCII 0x20-0x7E"
    return glyphs


def main():
    tiles = bytearray(128 * 16)
    for code, rows in parse().items():
        for y, row in enumerate(rows):
            bits = 0
            for x, px in enumerate(row):
                if px == "#":
                    bits |= 0x80 >> (x + 1)          # glyph in pixel columns 1-5
            tiles[code * 16 + y] = bits
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "font.chr")
    with open(out, "wb") as f:
        f.write(tiles)
    print("wrote", os.path.normpath(out), len(tiles), "bytes")


if __name__ == "__main__":
    main()
